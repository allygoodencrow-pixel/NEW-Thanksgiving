const {JSDOM}=require('jsdom');
const dom=new JSDOM('<body></body>',{url:'https://example.test/?demo=1'});
for(const k of ['window','document','HTMLElement','Node','localStorage','MutationObserver','Event','MouseEvent','KeyboardEvent','getComputedStyle'])global[k]=k==='getComputedStyle'?dom.window.getComputedStyle.bind(dom.window):dom.window[k];
Object.defineProperty(global,'navigator',{value:dom.window.navigator,configurable:true});
global.IS_REACT_ACT_ENVIRONMENT=true;window.scrollTo=()=>{};window.confirm=()=>true;
const React=require('react'),assert=require('node:assert/strict');
const {render,screen,cleanup,waitFor,fireEvent}=require('@testing-library/react');
const userEvent=require('@testing-library/user-event').default;
const {default:BuyerDemo,demoStorageKey,buyerSample}=require('../.qa/buyer-demo.cjs');
(async()=>{
 const user=userEvent.setup();
 localStorage.setItem('cc-thanksgiving-v4','production-plan-sentinel');
 localStorage.setItem('cc-thanksgiving-archive','production-archive-sentinel');
 localStorage.setItem('cc-party-sentinel','private-account-sentinel');
 render(React.createElement(BuyerDemo));
 assert(screen.getByRole('heading',{name:'THANKSGIVING',exact:true}));
 let saved=JSON.parse(localStorage.getItem(demoStorageKey));
 assert.equal(saved.guests.length,12);assert.equal(saved.guests.filter(g=>g.ageGroup==='Child').length,2);
 await user.click(screen.getByRole('button',{name:'START TOUR →'}));
 await waitFor(()=>assert(screen.getByRole('heading',{name:'Party plan',exact:true})));
 await user.click(screen.getByRole('button',{name:'NEXT →',exact:true}));
 await waitFor(()=>assert(screen.getByRole('heading',{name:'Guests',exact:true})));
 const rsvp=screen.getAllByLabelText(/^RSVP for /);
 const pending=rsvp.find(el=>el.value==='Pending');
 fireEvent.change(pending,{target:{value:'Declined'}});
 await waitFor(()=>assert.equal(JSON.parse(localStorage.getItem(demoStorageKey)).guests.filter(g=>g.rsvp==='Declined').length,1));
 const nav=['PLAN MENU','YOUR MENU','Shopping list','Your prep plan','Timeline','Activities','Seating + tables','Your budget','Printables'];
 for(const title of nav){await user.click(screen.getByRole('button',{name:'NEXT →'}));await waitFor(()=>assert(screen.getByRole('heading',{name:title,exact:true})));}
 const downloads=screen.getAllByRole('button').filter(b=>/DOWNLOAD PDF|DOWNLOAD THE COMPLETE COLLECTION/.test(b.textContent));
 assert(downloads.length>0);assert(downloads.every(b=>b.disabled));
 assert(screen.getAllByText('Preview available in your paid account').length>0);
 cleanup();render(React.createElement(BuyerDemo));
 assert.equal(JSON.parse(localStorage.getItem(demoStorageKey)).guests.filter(g=>g.rsvp==='Declined').length,1);
 await user.click(screen.getByRole('button',{name:'RESET SAMPLE'}));
 await waitFor(()=>assert.equal(JSON.parse(localStorage.getItem(demoStorageKey)).guests.filter(g=>g.rsvp==='Declined').length,0));
 assert.equal(localStorage.getItem('cc-thanksgiving-v4'),'production-plan-sentinel');
 assert.equal(localStorage.getItem('cc-thanksgiving-archive'),'production-archive-sentinel');
 assert.equal(localStorage.getItem('cc-party-sentinel'),'private-account-sentinel');
 assert.equal(screen.getByRole('link',{name:'CUSTOMER SIGN IN ↗'}).getAttribute('href'),'/');
 assert.equal(buyerSample().guests.length,12);
 cleanup();console.log('PASS buyer tour, RSVP edits, reload, reset, disabled paid downloads and customer-data isolation');
})().catch(e=>{console.error(e);cleanup();process.exit(1);});
